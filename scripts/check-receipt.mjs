import { createRequire } from "node:module";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createReceiptPdf } from "../dist/receipt.js";

const bundled = process.env.PORTAL_TEST_MODULES || process.argv[2];
const require = createRequire(`${bundled}/package.json`);
const sharp = require("sharp");
const { PDFDocument } = require("pdf-lib");
const png = await sharp(await readFile(new URL("../dist/logo.webp", import.meta.url))).png().toBuffer();
const metadata = await sharp(png).metadata();
const logo = { data: `data:image/png;base64,${png.toString("base64")}`, ratio: metadata.width / metadata.height };
const patient = { name: "Ren\u00e9e O'Connor (Follow-up)", phone: "+1 951 555 0100 / +1 951 555 0101 (caregiver)", reason: "Cognitive assessment", scheduled_date: "2026-10-12", notes: "Follow-up consultation completed." };
const doctor = { name: "Dr. Amina Shah", specialty: "Consultant Physician", registration: "Demo provider", clinic: "Body & Soul Health Center", address: "Corona, CA", email: "info@bodyandsoulhealthcenter.com" };
const blob = await createReceiptPdf(patient, doctor, { date: "October 12, 2026", time: "10:30 AM" }, "BS-20261012-TEST01", logo);
assert.equal(blob.type, "application/pdf");
const bytes = new Uint8Array(await blob.arrayBuffer());
assert.equal(new TextDecoder().decode(bytes.slice(0, 5)), "%PDF-");
const pdf = await PDFDocument.load(bytes);
assert.equal(pdf.getPageCount(), 1);
assert.equal(Math.round(pdf.getPage(0).getWidth()), 595);
assert.ok(bytes.length > png.length);
console.log(`Receipt valid: ${bytes.length} bytes, one A4 page, logo embedded, accented patient name handled.`);
assert.ok(new TextDecoder().decode(bytes).includes("Scheduled date"));
assert.ok(new TextDecoder().decode(bytes).includes("Follow-up consultation completed."));
const longBlob = await createReceiptPdf({ ...patient, notes: "Detailed follow-up notes. ".repeat(160) }, doctor, { date: "October 12, 2026", time: "10:30 AM" }, "BS-TEST-LONG", logo);
const longPdf = await PDFDocument.load(await longBlob.arrayBuffer());
assert.ok(longPdf.getPageCount() > 1);
console.log(`Long receipt valid: ${longPdf.getPageCount()} pages, notes paginate without overlapping the footer.`);
const detailed = await createReceiptPdf({...patient,date_of_birth:'1954-02-06',facility:'Saved Clinic',appointment_time:'3:30 PM',contact_person_name:'Alex Lee'},doctor,{date:'October 19, 2026',time:'10:30 AM'},'BS-DETAILS',logo);
const detailText = new TextDecoder().decode(await detailed.arrayBuffer());
for (const value of ['1954-02-06','Saved Clinic','3:30 PM','Alex Lee']) assert.ok(detailText.includes(value));
console.log('Structured patient details preserved in new PDF receipts.');
